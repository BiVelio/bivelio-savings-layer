import {
  agregar,
  dineroDe,
  etiquetas,
  isoUtc,
  textoEstable,
  validarGranularidad,
  validarMoneda,
} from "./agregado.js";
import { nombreDeProveedor } from "./proveedor.js";
import type { FocusExportOptions, FocusRow, SavingsRecord } from "./tipos.js";

// FILAS FOCUS 1.4 (Cost and Usage), la versión vigente (tag v1.4, 2026‑06‑04):
//   https://github.com/FinOps-Open-Cost-and-Usage-Spec/FOCUS_Spec/tree/v1.4/specification/datasets/cost_and_usage/columns
// Consultada el 2026‑09‑27. Las decisiones, cada una con la frase que la obliga:
//
//  · LOS CUATRO COSTES A 0. `BilledCost` «MUST reflect amounts as invoiced …
//    not estimated or inferred values» y «MUST be 0 for charges generated by
//    entities that are not responsible or authorized for invoicing, to avoid
//    double-counting». `EffectiveCost` «MUST be 0 for charges generated by
//    entities that do not originate the cost». BiVelio no factura ese gasto:
//    unida a la factura del proveedor, cada fila suma AHORRO y nunca gasto.
//    `ListCost` y `ContractedCost` son iguales a `BilledCost` sin precio unitario.
//  · `ChargeCategory = "Adjustment"`. Con "Usage" serían obligatorios `SkuId`,
//    `SkuPriceId` y `PricingQuantity`, que no existen sin inventar un SKU; con
//    "Adjustment" pueden ser null. `ConsumedQuantity` «MUST be null when
//    ChargeCategory is not "Usage"», así que no se emite.
//  · Nada de placeholders: null para lo ausente (NullHandling). Por eso un
//    proveedor que no se puede inferir es un TypeError y no un "Unknown".
//  · Columnas propias con prefijo `x_`, PascalCase alfanumérico, ≤ 50
//    caracteres y sin abreviaturas salvo `Id` (CustomColumnHandling).
//  · Fechas `YYYY-MM-DDTHH:mm:ssZ` en UTC; los fines, exclusivos.

const FN = "toFocusRows";
const SERVICIO_POR_DEFECTO = "BV-SALA savings ledger";
const PREFIJO_RESERVADO = "bivelio/";

interface Cuenta {
  id: string;
  nombre: string | null;
  subId: string | null;
  subNombre: string | null;
  tags: Record<string, string>;
}

function textoNoVacio(v: unknown): v is string {
  return typeof v === "string" && v.trim() !== "";
}

function resolverPorModelo(
  opcion: string | ((model: string) => string) | undefined,
  porDefecto: string | undefined,
  model: string,
  columna: string,
): string {
  const v = typeof opcion === "function" ? opcion(model) : (opcion ?? porDefecto);
  if (textoNoVacio(v)) return v;
  throw new TypeError(
    `[bvsala] ${FN}: cannot determine the FOCUS ${columna} for model "${model}". ` +
      `FOCUS allows no placeholder there: pass it in the options.`,
  );
}

function periodoDeFacturacion(
  inicioDelCargo: number,
  finDelCargo: number,
  opcion: FocusExportOptions["billingPeriod"],
): { start: number; end: number } {
  if (!opcion) {
    const d = new Date(inicioDelCargo);
    return {
      start: Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), 1),
      end: Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 1),
    };
  }
  const p = opcion(new Date(inicioDelCargo));
  const start = p?.start instanceof Date ? p.start.getTime() : Number.NaN;
  const end = p?.end instanceof Date ? p.end.getTime() : Number.NaN;
  if (!Number.isFinite(start) || !Number.isFinite(end) || start >= end) {
    throw new TypeError(`[bvsala] ${FN}: billingPeriod must return valid Dates with start before end`);
  }
  if (inicioDelCargo < start || finDelCargo > end) {
    throw new TypeError(`[bvsala] ${FN}: billingPeriod must contain the charge period it is given`);
  }
  return { start, end };
}

/**
 * Your SavingsReports as FOCUS 1.4 Cost and Usage rows, one per charge period
 * (UTC day by default), model, basis, billing account, sub account and tag set.
 *
 * Every cost column (`BilledCost`, `EffectiveCost`, `ListCost`,
 * `ContractedCost`) is 0 by design: your provider's bill already carries the
 * spend, so joining these rows with it adds savings and never adds cost.
 * `ChargeCategory` is "Adjustment" and nothing here invents a SKU or a price.
 *
 * The savings are in custom columns, one per basis: `x_BiVelioMeasuredSavings`,
 * `x_BiVelioReferenceSavings` and `x_BiVelioEstimatedSavings`; only the column
 * of the row's basis holds a value. `unmeasured` rows carry counts and null
 * money, and `shadow` reports are left out. `Tags` carries `bivelio/basis` and
 * `bivelio/model` plus your own tags.
 *
 * Throws a TypeError on an invalid `at`, currency or option, on a user tag
 * starting with "bivelio/", and when the provider of a model cannot be
 * derived and `serviceProviderName` is not given.
 */
export function toFocusRows(records: Iterable<SavingsRecord>, options: FocusExportOptions): FocusRow[] {
  if (!options || typeof options !== "object") {
    throw new TypeError(`[bvsala] ${FN}: options with a billingAccountId are required`);
  }
  const g = validarGranularidad(options.granularity, FN);
  const currency = validarMoneda(options.currency, FN);
  const { billingAccountId, billingAccountName, subAccount, tags } = options;
  if (typeof billingAccountId !== "function" && !textoNoVacio(billingAccountId)) {
    throw new TypeError(`[bvsala] ${FN}: billingAccountId must be a non-empty string or a function`);
  }
  const servicio = options.serviceName ?? SERVICIO_POR_DEFECTO;
  if (!textoNoVacio(servicio)) throw new TypeError(`[bvsala] ${FN}: serviceName must be a non-empty string`);

  const grupos = agregar<Cuenta>(records, g, FN, (r: SavingsRecord) => {
    const id = typeof billingAccountId === "function" ? billingAccountId(r) : billingAccountId;
    if (!textoNoVacio(id)) {
      throw new TypeError(
        `[bvsala] ${FN}: billingAccountId returned no id for request ${String(r.report.requestId)}`,
      );
    }
    const nombre = typeof billingAccountName === "function" ? billingAccountName(r) : billingAccountName;
    const sub = subAccount ? subAccount(r) : undefined;
    if (sub !== undefined && (!textoNoVacio(sub?.id) || !textoNoVacio(sub?.name))) {
      throw new TypeError(`[bvsala] ${FN}: subAccount must return { id, name } as non-empty strings, or undefined`);
    }
    const propias = etiquetas(tags ? tags(r) : undefined, "tags", FN);
    for (const k of Object.keys(propias)) {
      if (k.startsWith(PREFIJO_RESERVADO)) {
        throw new TypeError(`[bvsala] ${FN}: tag "${k}" uses the reserved "${PREFIJO_RESERVADO}" prefix`);
      }
    }
    const cuenta: Cuenta = {
      id,
      nombre: textoNoVacio(nombre) ? nombre : null,
      subId: sub ? sub.id : null,
      subNombre: sub ? sub.name : null,
      tags: propias,
    };
    return {
      clave: JSON.stringify([cuenta.id, cuenta.nombre, cuenta.subId, cuenta.subNombre, textoEstable(propias)]),
      extra: cuenta,
    };
  });

  return grupos.map((grupo): FocusRow => {
    const modelo = grupo.modelo;
    const proveedor = resolverPorModelo(
      options.serviceProviderName,
      nombreDeProveedor(modelo),
      modelo,
      "ServiceProviderName",
    );
    const emisor = resolverPorModelo(options.invoiceIssuerName, proveedor, modelo, "InvoiceIssuerName");
    const host = resolverPorModelo(options.hostProviderName, proveedor, modelo, "HostProviderName");
    const facturacion = periodoDeFacturacion(grupo.inicio, grupo.fin, options.billingPeriod);
    const dinero = dineroDe(grupo);
    const c = grupo.extra;
    const etiquetasDeLaFila: Record<string, string> = { "bivelio/basis": grupo.basis, "bivelio/model": modelo };
    for (const k of Object.keys(c.tags).sort()) etiquetasDeLaFila[k] = c.tags[k]!;
    // El ORDEN de estas claves es la cabecera del CSV: primero las columnas
    // FOCUS, luego las propias. test/exportador-serie-y-csv.test.ts lo fija.
    return {
      BilledCost: 0,
      EffectiveCost: 0,
      ListCost: 0,
      ContractedCost: 0,
      BillingCurrency: currency,
      BillingAccountId: c.id,
      BillingAccountName: c.nombre,
      BillingPeriodStart: isoUtc(facturacion.start),
      BillingPeriodEnd: isoUtc(facturacion.end),
      ChargePeriodStart: isoUtc(grupo.inicio),
      ChargePeriodEnd: isoUtc(grupo.fin),
      ChargeCategory: "Adjustment",
      ChargeClass: null,
      ChargeDescription:
        `BV-SALA savings ledger for ${modelo} (basis: ${grupo.basis}). ` +
        "Not a charge: cost columns are 0 by design.",
      ChargeFrequency: "Usage-Based",
      InvoiceIssuerName: emisor,
      ServiceProviderName: proveedor,
      HostProviderName: host,
      ServiceName: servicio,
      ServiceCategory: "AI and Machine Learning",
      ServiceSubcategory: "Generative AI",
      PricingQuantity: null,
      PricingUnit: null,
      SubAccountId: c.subId,
      SubAccountName: c.subNombre,
      Tags: JSON.stringify(etiquetasDeLaFila),
      x_BiVelioBasis: grupo.basis,
      x_BiVelioModelId: modelo,
      x_BiVelioRequestCount: grupo.peticiones,
      x_BiVelioProviderCallCount: grupo.llamadas,
      x_BiVelioAvoidedCallCount: grupo.evitadas,
      x_BiVelioBaselineCost: dinero.baseline,
      x_BiVelioActualCost: dinero.actual,
      x_BiVelioMeasuredSavings: dinero.measured,
      x_BiVelioReferenceSavings: dinero.reference,
      x_BiVelioEstimatedSavings: dinero.estimated,
      x_BiVelioEliminatedInputFloorCost: dinero.suelo,
      x_BiVelioBaselineInputTokens: grupo.tokens.baselineInput,
      x_BiVelioActualInputTokens: grupo.tokens.actualInput,
      x_BiVelioEliminatedInputTokens: grupo.tokens.eliminatedInput,
      x_BiVelioCompressedInputTokens: grupo.tokens.compressedInput,
      x_BiVelioProviderCachedInputTokens: grupo.tokens.providerCachedInput ?? null,
      x_BiVelioBaselineOutputTokens: grupo.tokens.baselineOutput,
      x_BiVelioActualOutputTokens: grupo.tokens.actualOutput,
      x_BiVelioEliminatedOutputTokens: grupo.tokens.eliminatedOutput,
    };
  });
}

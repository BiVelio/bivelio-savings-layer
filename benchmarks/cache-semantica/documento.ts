/**
 * El documento público de la precisión de la caché semántica, generado SOLO
 * desde el artefacto de una tirada en vivo. Puro: sin E/S, para probarlo con
 * artefactos sintéticos.
 *
 * Reglas de la plantilla (D21):
 *  · Toda cifra sale del artefacto. Lo único escrito a mano son definiciones y
 *    frases de las fuentes (el README del proyecto de las tripletas, la tarjeta
 *    del dataset y la página de ORCAS, con su URL en `fuentes.ts`).
 *  · El titular es el SUELO del intervalo de la precisión, no el punto.
 *  · Lo que no se midió se dice que no se midió.
 *  · Salida para el cliente, en inglés.
 */
import type { CI } from "../stats.js";
import { FUENTE_SEARCHQUERIES } from "./fuentes.js";
import type { Metricas } from "./nucleo.js";
import { intervalo, pct, type Artefacto } from "./publicar-verja.js";

export const RUTA_DOCUMENTO = "docs/SEMANTIC-CACHE-PRECISION.md";

export interface MetaDocumento {
  /** Ruta del artefacto versionado como evidencia, relativa a la raíz del repo. */
  rutaEvidencia: string;
  /** sha256 de esa copia, byte a byte. */
  sha256Evidencia: string;
}

const n = (x: number) => x.toLocaleString("en-US");
const fraccion = (k: number, d: number) => `${n(k)} / ${n(d)}`;
const suelo = (ci: CI | null | undefined) => pct(ci?.lower);

function filaTripletas(nombre: string, m: Metricas): string {
  const c = m.conteo;
  return (
    `| ${nombre} | ${n(c.casos)} | ${n(c.inciertos)} | ${n(c.aciertos)} | ${n(c.tp)} | ${n(c.fp)} | ` +
    `${intervalo(m.precision)} | ${intervalo(m.recall)} |`
  );
}

const CABECERA_TRIPLETAS = [
  "| Slice | Cases | Uncertain (excluded) | Reuses | Correct reuses | Wrong reuses | Precision [95 % CI] | Recall [95 % CI] |",
  "|---|---:|---:|---:|---:|---:|---|---|",
];

export function renderizarDocumento(a: Artefacto, meta: MetaDocumento): string {
  const t = a.tripletas;
  const s = a.lmarena;
  const total = t?.puntuacion.total;
  const precision = total?.precision;
  if (!t || !total || !precision) throw new Error("renderizarDocumento: the artifact has no triplet precision");
  const fecha = a.generatedAt.slice(0, 10);
  const c = a.config;
  const l: string[] = [];

  l.push("# Semantic cache precision");
  l.push("");
  l.push(
    `> Generated by \`pnpm cache-semantica:publicar\` from the measurement artifact \`${meta.rutaEvidencia}\` ` +
      `(sha256 \`${meta.sha256Evidencia}\`). Every figure on this page is read from that file; do not edit it by hand.`,
  );
  l.push("");
  l.push(
    `Measured on ${fecha} at commit \`${a.commit}\`, SDK ${a.sdkVersion}, Node ${a.node}. ` +
      "No model was called and no credential was used: the provider is a stand-in, and the only network traffic was " +
      "the download of public datasets at pinned revisions.",
  );
  l.push("");

  // ── 1. Qué se mide ──
  l.push("## What is measured");
  l.push("");
  l.push(
    "The semantic cache as it ships, driven through the whole layer (`createSavingsLayer`), not a re-implementation: " +
      "the built-in embedder, the default floors, the deterministic guard that compares figures, dates, negations and " +
      "content overlap turn by turn, and the policy that decides whether a request may use the cache at all.",
  );
  l.push("");
  l.push(`- Embedder: \`${c.embedder}\` (lexical: it scores word overlap, not meaning).`);
  l.push(`- Similarity floor: ${c.similarityFloor} (a stored request below it is not a candidate).`);
  l.push(
    `- Accept floor: ${c.acceptFloor} (the confidence a hit must reach; with no verifier configured, confidence is the similarity).`,
  );
  l.push(
    `- Effective floor: **${c.effectiveFloor}**, the higher of the two: confidence is the lower of the similarity and ` +
      "the verifier's score, so a hit needs a similarity at or above both floors. No verifier is configured here.",
  );
  l.push(
    `- Records kept: ${n(c.maxRecords)}${c.maxRecordsIsDefault ? " (the default)" : " (**not** the default)"}, evicted first in, first out.`,
  );
  l.push(
    "- Only the semantic cache is on (`exactCache: false`, `deterministicResolvers: false`), so every reuse counted " +
      "here is a semantic one. In a default setup the exact cache would answer a repeated request first.",
  );
  l.push("");
  l.push(
    "A **reuse** is a request answered with a stored answer instead of a provider call. **Precision** is the share of " +
      "reuses that were right to make. **Recall** is the share of the requests that could have been reused that were.",
  );
  l.push("");

  // ── 2. Titular ──
  l.push("## Headline");
  l.push("");
  l.push(
    `**Precision floor: ${suelo(precision)}.** That is the lower end of the 95 % Wilson interval for precision on ` +
      `the ${t.brazos.map((b) => `\`${b}\``).join(", ")} triplets: ${n(total.conteo.tp)} of the ` +
      `${n(total.conteo.tp + total.conteo.fp)} reuses were compatible with the request they answered ` +
      `(point estimate ${pct(precision.point)}).`,
  );
  l.push("");
  l.push(
    `Recall on the same cases: ${intervalo(total.recall)}. The cache reused ${n(total.conteo.tp)} of the ` +
      `${n(total.conteo.tp + total.conteo.fn)} requests labeled reusable; the rest went to the provider, as they would ` +
      "without the cache.",
  );
  l.push("");

  // ── 3. Tabla A ──
  l.push("## A. Triplets: GPTCache reuse_compatibility");
  l.push("");
  l.push(
    "Each case is a stored request, its stored answer and a new request, with a label saying whether the stored answer " +
      "can be reused as is for the new request. Each case runs in its own tenant, so cases are independent and the " +
      "intervals are Wilson score intervals. Cases labeled `uncertain` are left out of precision and recall and counted apart.",
  );
  l.push("");
  l.push(...CABECERA_TRIPLETAS);
  l.push(filaTripletas("**All measured cases**", total));
  const brazos = Object.entries(t.puntuacion.porBrazo);
  if (brazos.length > 1) for (const [b, m] of brazos) l.push(filaTripletas(`arm \`${b}\``, m));
  for (const [sp, m] of Object.entries(t.puntuacion.porSplit)) l.push(filaTripletas(`split \`${sp}\``, m));
  l.push("");
  const { noConsultados, sinGuardar } = t.puntuacion;
  if (noConsultados > 0 || sinGuardar > 0) {
    l.push(
      `The policy kept the cache out of ${n(noConsultados)} of the new requests, and out of ${n(sinGuardar)} more stored ` +
        "requests, which were then never written to it. It keeps out, among others, requests that look personal to a " +
        "user or that ask for fresh information. Both count as not reused: that is what the layer does.",
    );
    l.push("");
  }
  const categorias = Object.entries(t.puntuacion.categoriasFalsosPositivos).sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0]));
  if (categorias.length > 0) {
    l.push("Why the wrong reuses were labeled wrong (the dataset's `reason_categories`; a case can carry several):");
    l.push("");
    l.push("| Category | Wrong reuses |");
    l.push("|---|---:|");
    for (const [cat, k] of categorias) l.push(`| \`${cat}\` | ${n(k)} |`);
    l.push("");
  } else {
    l.push("There were no wrong reuses on these cases.");
    l.push("");
  }

  // ── 4. Tabla B ──
  if (s) {
    l.push("## B. Stream: SemBenchmarkLmArena");
    l.push("");
    l.push(
      `The first ${n(s.n)} prompts of the pinned revision, in dataset order, through one layer and one tenant. The stand-in ` +
        "provider answers with the class (`ID_Set`) of the prompt it was asked, so a reuse is correct when the class it " +
        "serves is the class of the prompt, the dataset card's definition of a correct hit. Whether a prompt is reused " +
        "depends on what earlier prompts left in the cache, so prompts are not independent: the intervals come from " +
        `resampling whole classes (${n(s.metricas.bootstrap.resamples)} resamples, fixed seed ${s.metricas.bootstrap.seed}, ` +
        `${n(s.clases)} classes).`,
    );
    l.push("");
    l.push("| Measure | Value [95 % CI] | Count |");
    l.push("|---|---|---:|");
    l.push(`| Reuse rate | ${intervalo(s.metricas.hitRate)} | ${fraccion(s.aciertos, s.consultas)} prompts |`);
    l.push(`| Precision | ${intervalo(s.metricas.precision)} | ${fraccion(s.correctos, s.aciertos)} reuses |`);
    l.push(`| Wrong reuse rate | ${intervalo(s.metricas.errorRate)} | ${fraccion(s.erroneos, s.consultas)} prompts |`);
    l.push(
      `| Recall vs reachable | ${intervalo(s.metricas.recallAlcanzable)} | ${fraccion(s.correctos, s.alcanzables)} prompts whose class was already cached |`,
    );
    l.push("");
    l.push(
      `- Records kept: ${n(s.maxRegistros)}; ${n(s.desalojos)} were evicted during the run.` +
        (s.noConsultados > 0 ? ` The policy kept the cache out of ${n(s.noConsultados)} prompts, which are left out of every row above.` : ""),
    );
    l.push(
      `- ${n(s.erroresConPromptIdentico)} of the ${n(s.erroneos)} wrong reuses served a stored prompt **identical** to the ` +
        `prompt asked, which the dataset files under a different class; ${n(s.promptsIdenticosEnVariasClases)} distinct prompts ` +
        "appear under more than one class in the rows used. Those count against precision here, but they are label noise, " +
        "not a cache error.",
    );
    l.push("");
  }

  // ── 5. Contexto ──
  if (t.contexto || a.verificacionPuntuador) {
    l.push("## Context: the project's own evaluator");
    l.push("");
    if (t.contexto) {
      const m = t.contexto.metricas;
      l.push(
        `On the same ${n(m.conteo.casos)} cases, ${t.contexto.evaluador}: precision ${intervalo(m.precision)}, recall ` +
          `${intervalo(m.recall)}. It is the project's evaluator, not this SDK's: it asks a model about every candidate, and ` +
          "its threshold was calibrated on this dataset (both per the project's README). It is shown to place the figures " +
          "above, not as a comparison on equal terms.",
      );
      l.push("");
    }
    const v = a.verificacionPuntuador;
    if (v) {
      l.push(
        v.ok
          ? `Scorer self-check: on all the triplets, the scorer used on this page reproduces the project's published ` +
              `figures for that evaluator exactly (${n(v.precision.k)} of its ${n(v.precision.n)} reuses correct, ` +
              `${n(v.recall.k)} of the ${n(v.recall.n)} cases labeled reusable).`
          : "Scorer self-check: FAILED.",
      );
      l.push("");
    }
  }

  // ── 6. Qué significa ──
  l.push("## What this means for you");
  l.push("");
  l.push(
    "- **Precision is the number to read.** A wrong reuse serves the answer to a different question and nothing " +
      "downstream flags it; a missed reuse only costs the provider call you would have made anyway.",
  );
  l.push(
    "- **It is opt-in three times over:** `savings.semanticCache` on the request (or `semanticCacheDefault` on " +
      "`createSavingsLayer`, for every request), a `semanticCache` passed to `createSavingsLayer`, and the " +
      "`semantic_cache` feature on your license. Passing the cache alone switches nothing on, and the layer warns " +
      "once when it has a cache that a request does not ask for.",
  );
  l.push(
    "- **It stays off on agentic traffic** (requests that declare tools, carry tool calls or tool results, or hold more " +
      'than one user turn) unless you set `savings.semanticCache: "include-agentic"`.',
  );
  l.push(
    "- **Measure it on your own traffic before you rely on it.** Every semantic reuse reports its similarity and the " +
      "floors it cleared in `report.qualityLedger.cacheMatch`, and `report.qualityStatus` marks it `task_equivalent`, never `exact`.",
  );
  l.push(
    "- This page measures whether a reused answer was right to reuse. It does not measure, and does not claim, what a reuse saves.",
  );
  l.push("");

  // ── 7. Límites ──
  l.push("## Limitations");
  l.push("");
  const fuentesEtiqueta = Object.entries(t.puntuacion.fuentesDeEtiqueta).sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0]));
  l.push(
    "- **The triplet labels are model-assisted**, not a human gold standard, as the project's README states. Label " +
      `sources among the measured cases: ${fuentesEtiqueta.map(([f, k]) => `\`${f}\` ${n(k)}`).join(", ")}.`,
  );
  l.push(
    "- **The labels judge reuse compatibility, not correctness.** They check whether the stored answer fits the new " +
      "request (task, entities, numbers, versions, explicit constraints, format, completeness), not whether that answer " +
      "is factually right. Some wrong reuses are wrong because of the stored answer rather than the question; the " +
      "category table above shows which.",
  );
  l.push(
    "- **The triplets are pre-selected pairs.** They are the candidate pairs of the original experiment, already picked " +
      "by semantic retrieval, so their reuse rate is not a production reuse rate (the project's README says the same).",
  );
  l.push(
    "- **Lexical embedder.** The built-in embedder sees word overlap only. Passing your own `embed` changes precision " +
      "and recall in ways this page does not measure.",
  );
  if (s) {
    l.push(
      "- **The stream's rewordings are model-written.** Per its dataset card, each class is one real LM-Arena prompt " +
        "plus variants generated by a model, not repeats observed in real traffic.",
    );
    l.push(
      "- **The stream is one ordering of one dataset.** Its figures depend on the order of the prompts and on the record " +
        "limit; label noise (identical prompts under different classes) lowers its measured precision.",
    );
  }
  l.push(
    "- **Not measured:** the two triplet arms whose prompts come from ORCAS (`search_llama`, `search_gpt`) and " +
      "SemBenchmarkSearchQueries, because ORCAS is licensed for non-commercial research only (see below).",
  );
  l.push(
    "- One model id is used for every request, served by the stand-in provider; it only takes part in the cache identity.",
  );
  l.push("");

  // ── 8. Datos y licencias ──
  l.push("## Data and licenses");
  l.push("");
  l.push("| Source | Revision | Fingerprint | License |");
  l.push("|---|---|---|---|");
  for (const f of a.fuentes) {
    const huella = f.sha256
      ? `sha256 \`${f.sha256.slice(0, 16)}…\``
      : `LFS oid \`${(f.lfsOid ?? "").slice(0, 16)}…\`${f.sha256Extraido ? `; extract sha256 \`${f.sha256Extraido.slice(0, 16)}…\`` : ""}`;
    l.push(`| [${f.nombre}](${f.url}) | \`${f.revision.slice(0, 12)}\` | ${huella} | [${f.licencia}](${f.urlLicencia}) |`);
  }
  l.push("");
  l.push(
    `Not used: [${FUENTE_SEARCHQUERIES.nombre}](${FUENTE_SEARCHQUERIES.url}) and the ORCAS-derived triplet arms. The ORCAS ` +
      `page states: "The MS MARCO and ORCAS datasets are intended for non-commercial research purposes only" ` +
      `(${FUENTE_SEARCHQUERIES.urlLicencia}). Sources consulted on ${a.fuentes[0]?.consultado ?? "n/a"}; full URLs and ` +
      "fingerprints are in the evidence file.",
  );
  l.push("");
  l.push(
    "Nothing from these datasets is redistributed from this repository: the evidence file holds case ids, reuse " +
      "decisions and similarity scores, and no prompt or answer text.",
  );
  l.push("");

  // ── 9. Reproducir ──
  l.push("## Reproduce");
  l.push("");
  l.push("```bash");
  l.push(`git checkout ${a.commit}`);
  l.push("pnpm install --frozen-lockfile");
  l.push("pnpm cache-semantica --descargar            # pinned revisions, verified by sha256 / LFS oid");
  l.push("pnpm cache-semantica --verificar-puntuador  # must reproduce the project's published figures");
  l.push(`pnpm cache-semantica --conjunto todos --n ${s ? s.n : 20000}${c.maxRecordsIsDefault ? "" : ` --max-registros ${c.maxRecords}`}`);
  l.push("pnpm cache-semantica:publicar --dry-run");
  l.push("```");
  l.push("");
  return l.join("\n");
}

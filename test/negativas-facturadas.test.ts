const itemResponses = (parte: unknown) => ({ id: "msg_1234567890", type: "message", status: "completed", role: "assistant", content: [parte] });
const PARTE_NEGATIVA = { type: "refusal", refusal: TEXTO_NEGATIVA_OPENAI };
const PARTE_TEXTO = { type: "output_text", text: '{"answer":"42"}', annotations: [] };
/** El ejemplo oficial de la Responses API: una respuesta `completed` cuya única parte es `refusal`. */
const respuestaResponses = (parte: unknown) => ({
  id: "resp_1234567890",
  object: "response",
  created_at: 1721596428,
  status: "completed",
  error: null,
  incomplete_details: null,
  model: "gpt-4o-mini",
  output: [itemResponses(parte)],
  service_tier: "default",
  usage: { input_tokens: 81, output_tokens: 11, total_tokens: 92, output_tokens_details: { reasoning_tokens: 0 } },
});
const evResponses = (datos: { type: string } & Record<string, unknown>): string => `event: ${datos.type}\ndata: ${JSON.stringify(datos)}\n\n`;
/** La misma negativa en stream, con los eventos de la referencia oficial. */
function sseResponses(parte: typeof PARTE_NEGATIVA | typeof PARTE_TEXTO): string {
  const final = respuestaResponses(parte);
  const enCurso = { ...final, status: "in_progress", output: [], usage: null };
  const vacia = parte.type === "refusal" ? { type: "refusal", refusal: "" } : { ...PARTE_TEXTO, text: "" };
  const delta =
    parte.type === "refusal"
      ? [
          evResponses({ type: "response.refusal.delta", item_id: "msg_1234567890", output_index: 0, content_index: 0, delta: "I'm sorry, ", sequence_number: 4 }),
          evResponses({ type: "response.refusal.delta", item_id: "msg_1234567890", output_index: 0, content_index: 0, delta: "I cannot assist with that request.", sequence_number: 5 }),
          evResponses({ type: "response.refusal.done", item_id: "msg_1234567890", output_index: 0, content_index: 0, refusal: TEXTO_NEGATIVA_OPENAI, sequence_number: 6 }),
        ]
      : [
          evResponses({ type: "response.output_text.delta", item_id: "msg_1234567890", output_index: 0, content_index: 0, delta: PARTE_TEXTO.text, sequence_number: 4 }),
          evResponses({ type: "response.output_text.done", item_id: "msg_1234567890", output_index: 0, content_index: 0, text: PARTE_TEXTO.text, sequence_number: 5 }),
        ];
  return [
    evResponses({ type: "response.created", response: enCurso, sequence_number: 0 }),
    evResponses({ type: "response.in_progress", response: enCurso, sequence_number: 1 }),
    evResponses({ type: "response.output_item.added", output_index: 0, item: { ...itemResponses(vacia), status: "in_progress", content: [] }, sequence_number: 2 }),
    evResponses({ type: "response.content_part.added", item_id: "msg_1234567890", output_index: 0, content_index: 0, part: vacia, sequence_number: 3 }),
    ...delta,
    evResponses({ type: "response.content_part.done", item_id: "msg_1234567890", output_index: 0, content_index: 0, part: parte, sequence_number: 7 }),
    evResponses({ type: "response.output_item.done", output_index: 0, item: itemResponses(parte), sequence_number: 8 }),
    evResponses({ type: "response.completed", response: final, sequence_number: 9 }),
  ].join("");
}

